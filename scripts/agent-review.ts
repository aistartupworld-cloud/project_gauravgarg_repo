// Headless reviewer: runs the `reviewer` agent through the Claude Agent SDK against the current branch's diff.
// Used by CI (`npm run agent:review`) and locally. Needs ANTHROPIC_API_KEY; `--dry-run` prints the prompt only.
//
//   BASE_REF=origin/main npm run agent:review            # review, write specs/reviews/agent-review.md
//   npm run agent:review -- --dry-run                    # show what would be sent
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { query, type McpServerConfig } from '@anthropic-ai/claude-agent-sdk';

const ROOT = resolve(import.meta.dirname, '..');
const BASE_REF = process.env.BASE_REF ?? 'main';
const MODEL = process.env.REVIEW_MODEL ?? 'claude-opus-5-5';
const OUT = join(ROOT, 'specs/reviews/agent-review.md');
const dryRun = process.argv.includes('--dry-run');

const git = (...args: string[]) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' }).trim();

const changed = git('diff', '--name-only', `${BASE_REF}...HEAD`).split('\n').filter(Boolean);
if (changed.length === 0) {
  console.log(`No changes against ${BASE_REF}; nothing to review.`);
  process.exit(0);
}

const contracts = changed.filter((f) => f.startsWith('sprint-contracts/'));
const mcp = JSON.parse(readFileSync(join(ROOT, '.mcp.json'), 'utf8')) as { mcpServers: Record<string, McpServerConfig> };

const prompt = `You are the SecureGate reviewer agent (see .claude/agents/reviewer.md). Review branch HEAD against ${BASE_REF}.

Changed files:
${changed.map((f) => `- ${f}`).join('\n')}

${contracts.length ? `Sprint contract(s) touched: ${contracts.join(', ')}. Grade against their evaluator checklist.` : 'No sprint contract changed: grade against specs/app_spec.md and the feature specs the diff touches.'}

Do this, in order:
1. Read CLAUDE.md and the CLAUDE.md of every layer the diff touches. Specs in specs/ are the source of truth.
2. Run: npm run typecheck, npm test, npm run lint:deps, npm run ac:trace. Record exact pass/fail counts.
3. Read the diff (git diff ${BASE_REF}...HEAD) and check: layering rules, append-only tables, integer-day SLA maths,
   requireRole on every route, separation of duties (owner, raising auditor and evidence uploader never decide),
   no secrets or real personal data, every new behaviour covered by an [AC-xx]/[NFR-xx]-tagged test.
4. If the UI changed and the Playwright MCP tools are available, start the app and walk the affected journey.

Reply with a Markdown review: first line exactly "Verdict: PASS", "Verdict: RATCHET" or "Verdict: FAIL", then a
table of checks with evidence, then numbered defects with file:line and reproduction steps. Do not edit files.`;

if (dryRun) {
  console.log(prompt);
  process.exit(0);
}
if (!process.env.ANTHROPIC_API_KEY) {
  console.error('ANTHROPIC_API_KEY is not set; run with --dry-run to preview the review prompt.');
  process.exit(2);
}

let report = '';
let cost = 0;
for await (const message of query({
  prompt,
  options: {
    cwd: ROOT,
    model: MODEL,
    settingSources: ['project'], // loads CLAUDE.md files, .claude/agents, skills and hooks
    mcpServers: mcp.mcpServers,
    allowedTools: ['Read', 'Glob', 'Grep', 'Bash(npm run *)', 'Bash(npm test)', 'Bash(git diff *)', 'Bash(git log *)', 'mcp__playwright__*'],
    disallowedTools: ['Edit', 'Write', 'MultiEdit'],
    permissionMode: 'dontAsk',
    maxTurns: 40,
  },
})) {
  if (message.type === 'result') {
    cost = message.total_cost_usd;
    if (message.subtype === 'success' && !message.is_error) report = message.result;
    else {
      console.error(`Review run ended early: ${message.subtype}`);
      process.exit(2);
    }
  }
}

const header = `<!-- generated by scripts/agent-review.ts · model ${MODEL} · base ${BASE_REF} · head ${git('rev-parse', '--short', 'HEAD')} · ~$${cost.toFixed(2)} -->\n`;
writeFileSync(OUT, header + report + '\n');
console.log(report);

const verdict = /^Verdict:\s*(PASS|RATCHET|FAIL)/m.exec(report)?.[1] ?? 'FAIL';
console.log(`\nVerdict ${verdict} — written to ${OUT}`);
process.exit(verdict === 'PASS' ? 0 : 1);
